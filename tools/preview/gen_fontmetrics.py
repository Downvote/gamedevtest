#!/usr/bin/env python3
"""Generates fontmetrics.luau and fontmetrics.json: per-font advance widths (units per 1000 em), ascent/descent and
the glyph coverage of the preview fonts, so the Luau GUI layout (TextBounds, AutomaticSize, TextScaled, wrapping) and
the Python drawing break text identically.
Usage: gen_fontmetrics.py <outdir>"""
import json
import os
import sys

from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from topng import FONT_FILES  # noqa: E402

RANGES = [(32, 127), (160, 384), (0x2010, 0x2030), (0x2030, 0x2060), (0x20A0, 0x20C0), (0x2190, 0x2200),
          (0x2200, 0x2300), (0x25A0, 0x2600), (0x2600, 0x2700), (0x2700, 0x27C0), (0x2B00, 0x2B60), (0x3000, 0x3004)]
SIZE = 1000


def coverage(f):
    notdef = f.getmask("\U0010fffd")
    sig = (notdef.size, bytes(notdef))
    out = {}
    for a, b in RANGES:
        for cp in range(a, b):
            ch = chr(cp)
            if cp == 32:
                out[cp] = f.getlength(" ")
                continue
            m = f.getmask(ch)
            if (m.size, bytes(m)) == sig:
                continue
            out[cp] = f.getlength(ch)
    return out


def main(outdir):
    data = {}
    for key, path in FONT_FILES.items():
        f = ImageFont.truetype(path, SIZE)
        asc, desc = f.getmetrics()
        data[key] = {"asc": asc, "desc": desc, "adv": {str(k): round(v, 2) for k, v in coverage(f).items()}}
    with open(os.path.join(outdir, "fontmetrics.json"), "w") as fh:
        json.dump(data, fh)
    lines = ["-- generated by gen_fontmetrics.py: advance widths per 1000 em, ascent/descent, coverage", "return {"]
    for key, d in data.items():
        lines.append("\t%s = { asc = %d, desc = %d, adv = {" % (key, d["asc"], d["desc"]))
        items = sorted((int(k), v) for k, v in d["adv"].items())
        row = []
        for cp, v in items:
            row.append("[%d] = %s" % (cp, repr(v)))
            if len(row) == 12:
                lines.append("\t\t" + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("\t\t" + ", ".join(row) + ",")
        lines.append("\t} },")
    lines.append("}")
    with open(os.path.join(outdir, "fontmetrics.luau"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("fonts:", ", ".join(f"{k} ({len(v['adv'])} glyphs)" for k, v in data.items()))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else HERE)
