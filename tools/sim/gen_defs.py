#!/usr/bin/env python3
"""Parse luau-lsp's Roblox globalTypes.d.luau into a Luau table of classes (props/events/methods) and enums.
Usage: gen_defs.py <globalTypes.d.luau> <out.luau>"""
import json
import re
import sys

src, out = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8").read().split("\n")

meta = {}
if lines[0].startswith("--#METADATA#"):
    meta = json.loads(lines[0][len("--#METADATA#"):])

classes = {}
enums = {}
cur = None
kind = None
skip_next = False
hdr = re.compile(r"^declare extern type (\w+)(?: extends (\w+))? with")
for raw in lines:
    m = hdr.match(raw)
    if m:
        name, sup = m.group(1), m.group(2)
        if name.startswith("Enum") and name.endswith("_INTERNAL"):
            cur = {"items": []}
            enums[name[4:-9]] = cur
            kind = "enum"
        else:
            cur = {"super": sup, "props": {}, "events": {}, "methods": {}}
            classes[name] = cur
            kind = "class"
        if raw.rstrip().endswith(" end"):
            cur = None
        continue
    if cur is None:
        continue
    s = raw.strip()
    if s == "end":
        cur = None
        continue
    if s.startswith("@"):
        # decorator: the next member is deprecated; keep it anyway (still valid at runtime)
        continue
    if kind == "enum":
        mm = re.match(r"^(\w+): Enum\w+", s)
        if mm:
            cur["items"].append(mm.group(1))
        continue
    mm = re.match(r"^function (\w+)\(", s)
    if mm:
        cur["methods"][mm.group(1)] = True
        continue
    mm = re.match(r"^(\w+): (.+)$", s)
    if mm:
        pname, ptype = mm.group(1), mm.group(2).strip()
        if ptype.startswith("RBXScriptSignal"):
            cur["events"][pname] = True
        else:
            cur["props"][pname] = ptype
        continue

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

o = ["-- generated by gen_defs.py from luau-lsp globalTypes.d.luau; do not edit", "local C = {}"]
for name, c in sorted(classes.items()):
    props = ", ".join("[%s]=%s" % (lua_str(k), lua_str(v)) for k, v in sorted(c["props"].items()))
    events = ", ".join("[%s]=true" % lua_str(k) for k in sorted(c["events"]))
    methods = ", ".join("[%s]=true" % lua_str(k) for k in sorted(c["methods"]))
    sup = lua_str(c["super"]) if c["super"] else "nil"
    o.append("C[%s] = {super=%s, props={%s}, events={%s}, methods={%s}}" % (lua_str(name), sup, props, events, methods))
o.append("local E = {}")
for name, e in sorted(enums.items()):
    o.append("E[%s] = {%s}" % (lua_str(name), ", ".join(lua_str(i) for i in e["items"])))
cre = meta.get("CREATABLE_INSTANCES", [])
o.append("local CR = {%s}" % ", ".join("[%s]=true" % lua_str(x) for x in cre))
o.append("return { classes = C, enums = E, creatable = CR }")
open(out, "w", encoding="utf-8").write("\n".join(o) + "\n")
print("classes", len(classes), "enums", len(enums), "creatable", len(cre))
