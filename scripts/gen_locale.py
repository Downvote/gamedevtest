#!/usr/bin/env python3
# scripts/gen_locale.py: regenerates src/shared/Locale/<code>.luau from locale/<code>.json (docs/LOCALIZATION.md 5).
#
#   python3 scripts/gen_locale.py            every language in locale/
#   python3 scripts/gen_locale.py es ru      only these
#
# locale/<code>.json is the language's table, English -> its words, and the place to edit them: a key is a whole
# string as the game shows it or a template ("{1} of {2} bought"); its translation keeps every {n} (in any order) and
# every rich-text tag (<font color="#...">...</font>); named slots ({name}, Lang.fmt) too. An entry that drops or adds one, or is empty, is left out with a
# warning (the game then shows that string in English) and the script exits 1.
import json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "locale")
OUT = os.path.join(ROOT, "src", "shared", "Locale")
CODES = ["id", "es", "th", "pt", "ar", "ru", "fr", "zh", "it"]


def marks(s):
    out = re.findall(r"\{\w+\}", s)
    out += [re.sub(r"\s", "", m) for m in re.findall(r"</?font[^>]*>", s)]
    return sorted(out)


def lua_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "").replace("\t", "\\t")
    return '"' + s + '"'


def build(code):
    path = os.path.join(SRC, code + ".json")
    words = json.load(open(path, encoding="utf-8"))
    ok, bad = {}, []
    for key, out in words.items():
        if not isinstance(out, str) or not out.strip():
            bad.append((key, "empty"))
        elif marks(out) != marks(key):
            bad.append((key, "placeholders or tags differ: %r" % out))
        else:
            ok[key] = out
    lines = [
        "--!strict",
        "-- GENERATED by scripts/gen_locale.py from locale/%s.json (docs/LOCALIZATION.md 5): edit the JSON, not this." % code,
        "-- English -> the language's words; keys with {n} are templates (Locale/Lang).",
        "-- stylua: ignore start",
        "return {",
    ]
    for key in sorted(ok):
        lines.append("\t[%s] = %s," % (lua_str(key), lua_str(ok[key])))
    lines += ["}", "-- stylua: ignore end", ""]
    open(os.path.join(OUT, code + ".luau"), "w", encoding="utf-8").write("\n".join(lines))
    for key, why in bad:
        print("  %s: %r: %s" % (code, key[:80], why))
    print("%s: %d strings%s" % (code, len(ok), " (%d left out)" % len(bad) if bad else ""))
    return not bad


def main():
    codes = sys.argv[1:] or [c for c in CODES if os.path.exists(os.path.join(SRC, c + ".json"))]
    good = True
    for code in codes:
        good = build(code) and good
    sys.exit(0 if good else 1)


if __name__ == "__main__":
    main()
